export const tourById = (id: string) => TOURS.find((t) => t.id === id);

/** Аяллыг сонгосон хэлээр буцаана. Тоо баримт (өдөр, үнэ, сар) хоёр хэлэнд ижил. */
export function localizeTour(t: Tour, lang: Lang): Tour {
  if (lang === 'mn') return t;
  const en = TOURS_EN[t.id];
  return en ? { ...t, ...en, titleEn: '' } : t;
}

export const toursIn = (lang: Lang): Tour[] => TOURS.map((t) => localizeTour(t, lang));
